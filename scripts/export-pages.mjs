#!/usr/bin/env node
// Export the results for the GitHub Pages deck in docs/:
//   docs/data.js        window.BAKEOFF = { models, harnesses, tasks, runs }
//   docs/shots/*.jpg    1440px desktop screenshots, downsized
// Only fields that are safe to publish are copied: no local paths, logs or raw
// model streams. Uses the latest graded run per task × model × harness.
//   node scripts/export-pages.mjs
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const { MODELS, HARNESSES, TASKS, NEUTRAL } = await import(path.join(ROOT, 'models.mjs'));
const DOCS = path.join(ROOT, 'docs');
const SHOTS = path.join(DOCS, 'shots');
fs.mkdirSync(SHOTS, { recursive: true });

const all = fs.readFileSync(path.join(ROOT, 'results', 'runs.jsonl'), 'utf8').split('\n').filter(Boolean).map((l) => JSON.parse(l));
const latest = new Map();
for (const r of all) {
  const k = `${r.taskId || 'pomodoro'}|${r.model}|${r.harness}`;
  if (!latest.has(k) || r.at > latest.get(k).at) latest.set(k, r);
}

const labels = {};
const runs = [];
for (const r of latest.values()) {
  const task = r.taskId || 'pomodoro';
  const dir = path.join(ROOT, 'results', 'runs', r.runId);
  try {
    const g = JSON.parse(fs.readFileSync(path.join(dir, 'grade.json'), 'utf8'));
    labels[task] ||= g.checks.map((c) => ({ id: c.id, label: c.label }));
  } catch { /* no grade file */ }
  let shot = null;
  const png = path.join(dir, 'desktop.png');
  if (fs.existsSync(png)) {
    shot = `shots/${task}-${r.model}-${r.harness}.jpg`;
    execFileSync('sips', ['-s', 'format', 'jpeg', '-s', 'formatOptions', '72', '-Z', '1200', png, '--out', path.join(DOCS, shot)], { stdio: 'ignore' });
  }
  runs.push({
    task, model: r.model, harness: r.harness, repeat: r.repeat, at: r.at, status: r.status,
    wallMs: r.wallMs, ttftMs: r.ttftMs, apiRequests: r.apiRequests, agentTurns: r.agentTurns,
    outputTokens: r.tokens?.output ?? null, thinkTokens: r.thinkTokens ?? null,
    tokPerSec: r.tokPerSec, costUsd: r.costUsd, toolErrors: r.toolErrors, toolCounts: r.toolCounts,
    passed: r.grade?.passed ?? null, total: r.grade?.total ?? null,
    failed: (r.grade?.failed || []).map((f) => ({ id: f.id, label: f.label, detail: f.detail })),
    files: (r.files || []).map((f) => ({ name: f.name, lines: f.lines, bytes: f.bytes })),
    shot,
  });
}

const data = {
  generated: new Date().toISOString(),
  models: MODELS.map((m) => ({
    id: m.id, name: m.name, vendor: m.vendor, kind: m.kind, quant: m.quant || null, params: m.params,
    repo: m.repo || null, file: m.file || null, ctx: m.ctx || null, reasoningEffort: m.reasoningEffort || 'medium',
    sampling: m.sampling || null, model: m.model || null, bedrockModel: m.bedrockModel || null, pricing: m.pricing || null,
  })),
  harnesses: HARNESSES,
  neutral: NEUTRAL,
  tasks: TASKS.map((t) => ({ id: t.id, title: t.title, level: t.level, skill: t.skill, prompt: t.prompt, seeded: !!t.seed, checks: labels[t.id] || [] })),
  runs: runs.sort((a, b) => a.task.localeCompare(b.task) || a.model.localeCompare(b.model) || a.harness.localeCompare(b.harness)),
};
fs.writeFileSync(path.join(DOCS, 'data.js'), `// Generated by scripts/export-pages.mjs — do not edit by hand.\nwindow.BAKEOFF = ${JSON.stringify(data, null, 1)};\n`);
console.log(`exported ${runs.length} runs, ${fs.readdirSync(SHOTS).length} screenshots → docs/`);
